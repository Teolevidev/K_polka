-- Чужие полки становятся видны - иначе клуб не работает.
--
-- До сих пор user_books читал только владелец, поэтому ни лента
-- активности, ни «полки участников» физически не могли ничего показать:
-- запрос возвращал пусто, а не отказ, и выглядело это как пустая лента.
--
-- Открываем только полки НЕприватных профилей. У кого в профиле стоит
-- is_private, того полка по-прежнему видна лишь ему самому - ровно так
-- же, как уже устроена видимость самих профилей.
--
-- Старая политика "user_books own" остается: она дает владельцу запись,
-- а разрешительные политики складываются по ИЛИ.

drop policy if exists "user_books public read" on user_books;

create policy "user_books public read" on user_books for select using (
  user_id = auth.uid()
  or exists (
    select 1 from profiles p
    where p.id = user_books.user_id and not p.is_private
  )
);
