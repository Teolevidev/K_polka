import type { LongreadPayload, ReviewPayload, RoundupPayload } from './types';

/**
 * Промпты контент-агента.
 *
 * Лежат отдельным файлом и под гитом намеренно: промпт - такой же
 * исходник, как код. Когда текст поедет, нужно видеть в истории, что
 * именно поменялось в задании модели, а не гадать.
 */

export interface BookFacts {
  title: string;
  authors: string[];
  description: string | null;
  publishedYear: number | null;
  publisher: string | null;
  pageCount: number | null;
  language: string | null;
}

/**
 * Общая часть для всех текстовых заданий.
 *
 * Три вещи, которые здесь важнее стиля:
 *  - правила текста проекта. Без них модель ставит «ё» и длинное тире
 *    в каждом абзаце, и потом это чинится руками;
 *  - запрет выдумывать. Модель охотно сочиняет тиражи, премии и
 *    обстоятельства написания, и звучит это убедительно;
 *  - честная роль. Текст редакционный, и делать вид, что его написал
 *    участник клуба со своей полкой, нельзя.
 */
export const SYSTEM_PROMPT = [
  'Ты пишешь для «Книжной полки» - закрытого книжного клуба и трекера прочитанного.',
  'Аудитория: полтора десятка взрослых читающих людей, коллеги и знакомые.',
  '',
  'ПРАВИЛА ТЕКСТА (обязательны, нарушение - брак):',
  '1. Всегда пиши обычную букву «е». Никогда не используй «е» с двумя точками.',
  '2. Не используй длинное и среднее тире. Только дефис.',
  '3. Пиши по-русски, живо и без канцелярита. Без восклицательных знаков.',
  '4. Не начинай ответ с обращения к читателю задания («Конечно», «Вот статья»).',
  '   Первая строка ответа - уже сам текст.',
  '',
  'ЧЕСТНОСТЬ (важнее складности):',
  '5. Опирайся ТОЛЬКО на факты, которые даны тебе в задании.',
  '   Не придумывай тиражи, премии, продажи, даты, цитаты и биографию автора.',
  '6. Если чего-то не знаешь - не пиши об этом вовсе. Пропуск лучше выдумки.',
  '7. Не пересказывай сюжет до развязки и не раскрывай финал.',
  '8. Ты пишешь от лица редакции клуба, а не от лица участника.',
  '   Не изображай личный читательский опыт: «я читал это в поезде» - ложь.',
  '   Можно: «редакция советует», «книга из тех, что».',
].join('\n');

/** Факты о книге в том виде, в каком они уходят в промпт. */
export function formatBookFacts(book: BookFacts): string {
  const lines = [
    `Название: ${book.title}`,
    `Автор: ${book.authors.join(', ') || 'не указан'}`,
  ];
  if (book.publishedYear) lines.push(`Год издания: ${book.publishedYear}`);
  if (book.publisher) lines.push(`Издательство: ${book.publisher}`);
  if (book.pageCount) lines.push(`Объем: ${book.pageCount} страниц`);
  if (book.language) lines.push(`Язык издания: ${book.language}`);
  if (book.description) {
    lines.push('', 'Аннотация издателя:', book.description.slice(0, 2000));
  } else {
    lines.push('', 'Аннотации нет. Это значит, что о содержании книги тебе');
    lines.push('известно только название и автор - пиши исходя из этого и не');
    lines.push('домысливай сюжет.');
  }
  return lines.join('\n');
}

/** Формат ответа: один JSON, без markdown-обертки. */
const JSON_CONTRACT = [
  'Ответь ОДНИМ объектом JSON без markdown-ограждения:',
  '{',
  '  "title": "заголовок статьи, до 90 знаков, без кавычек по краям",',
  '  "excerpt": "одно предложение для карточки в блоге, до 200 знаков",',
  '  "bodyMd": "текст статьи в markdown"',
  '}',
  'Внутри bodyMd допустимы подзаголовки уровня ## и списки. Заголовка # быть не должно.',
].join('\n');

/** Рецензия: разбор одной книги. */
export function reviewPrompt(book: BookFacts, payload: ReviewPayload): string {
  return [
    'Напиши редакционный обзор книги для блога клуба.',
    '',
    'ФАКТЫ О КНИГЕ:',
    formatBookFacts(book),
    '',
    payload.angle ? `УГОЛ ЗРЕНИЯ: ${payload.angle}` : '',
    '',
    'Что должно быть в тексте:',
    '- о чем книга, без спойлеров и без пересказа развязки;',
    '- чем она хороша и кому подойдет, а кому нет;',
    '- одна честная оговорка: чего в книге ждать не стоит.',
    '',
    'Объем: 1800-3500 знаков. Это обзор, а не аннотация и не диссертация.',
    '',
    JSON_CONTRACT,
  ]
    .filter(Boolean)
    .join('\n');
}

/** Лонгрид: тема, вокруг которой могут стоять несколько книг. */
export function longreadPrompt(payload: LongreadPayload, books: BookFacts[]): string {
  const booksBlock =
    books.length > 0
      ? [
          'КНИГИ, КОТОРЫЕ ЕСТЬ В КАТАЛОГЕ КЛУБА (упоминай только их):',
          ...books.map(
            (b, i) =>
              `${i + 1}. «${b.title}» - ${b.authors.join(', ')}${
                b.publishedYear ? `, ${b.publishedYear}` : ''
              }`,
          ),
        ].join('\n')
      : 'Книг в задании нет: пиши о теме, а конкретные книги называй только те,\nв существовании которых уверен.';

  return [
    `Напиши лонгрид для блога клуба на тему: ${payload.topic}`,
    '',
    booksBlock,
    '',
    payload.angle ? `УГОЛ ЗРЕНИЯ: ${payload.angle}` : '',
    '',
    'Это не список и не обзор. Это связный текст с одной мыслью, которую',
    'читатель унесет с собой. Начни с наблюдения, а не с определения.',
    '',
    'Объем: 4000-9000 знаков. Подзаголовки уровня ## приветствуются.',
    '',
    JSON_CONTRACT,
  ]
    .filter(Boolean)
    .join('\n');
}

/** Подборка: несколько книг каталога вокруг темы. */
export function roundupPrompt(payload: RoundupPayload, books: BookFacts[]): string {
  return [
    `Собери подборку книг на тему: ${payload.theme}`,
    '',
    'Книги бери ТОЛЬКО из этого списка - это каталог клуба.',
    'Выбери те, что действительно подходят под тему, остальные не упоминай.',
    'Если под тему подходит меньше трех книг - так и напиши в тексте.',
    '',
    ...books.map(
      (b, i) =>
        `${i + 1}. «${b.title}» - ${b.authors.join(', ')}${
          b.publishedYear ? `, ${b.publishedYear}` : ''
        }${b.description ? `. ${b.description.slice(0, 300)}` : ''}`,
    ),
    '',
    'На каждую выбранную книгу - абзац: почему она здесь и кому зайдет.',
    'Объем: 1500-4000 знаков.',
    '',
    JSON_CONTRACT,
  ].join('\n');
}
